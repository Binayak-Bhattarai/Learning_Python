# a simple program to print area and perimeter of a rectangale with user provided values for length and breadth

length=float(input("Enter the length of rectangle: "))
breadth=float(input("Enter the breadth of rectangle: "))

area= length*breadth
perimeter=2*(length+breadth)

print("Area of rectange with length",length,"and breadth",breadth,"is:",area ,"sq.unit")
print("Perimeter of rectange with length",length,"and breadth",breadth,"is:",perimeter,"unti")
